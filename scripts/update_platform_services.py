from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "docs" / "platform-team-services.md"
RUNTIME = ROOT / ".data" / "platform-services"
DEPARTMENT_ID = 3
DEPARTMENT_SLUG = "platform"
TIMEZONE = ZoneInfo("Asia/Shanghai")
MARKER = "<!-- Generated by scripts/update_platform_services.py. -->"


class InventoryError(RuntimeError):
    """A safe error that never includes authentication or raw command output."""


class Cockpit:
    def __init__(self, binary="cockpit"):
        self.binary = binary

    def get(self, path, params):
        try:
            result = subprocess.run(
                [self.binary, "api", "GET", path + "?" + urlencode(params), "-o", "json"],
                capture_output=True, text=True, timeout=60,
            )
        except (OSError, subprocess.TimeoutExpired):
            raise InventoryError(f"cockpit 请求未完成：{path}") from None
        if result.returncode:
            raise InventoryError(f"cockpit 请求失败：{path}；请检查网络和 cockpit 登录状态。")
        try:
            return json.loads(result.stdout)
        except (ValueError, TypeError):
            raise InventoryError(f"cockpit 未返回有效 JSON：{path}") from None


def fetch_all(client, path, params=None, *, page_size=200):
    """Reject partial, duplicate, changing, or unexpectedly paginated catalogs."""
    rows, seen, expected_total = [], set(), None
    for page in range(1000):
        body = client.get(path, {**(params or {}), "pageSize": page_size, "pageIndex": page})
        if not isinstance(body, dict) or not isinstance(body.get("data"), list):
            raise InventoryError(f"目录响应结构不完整：{path}")
        total, size = body.get("totalCount"), body.get("pageSize")
        if (
            type(total) is not int or total < 0 or type(size) is not int or size < 1
            or type(body.get("page")) is not int or body["page"] != page
            or size > page_size or len(body["data"]) > size
        ):
            raise InventoryError(f"目录分页信息无法核验：{path}")
        if expected_total is None:
            expected_total = total
        elif total != expected_total:
            raise InventoryError(f"抓取期间目录数量变化，请重新运行：{path}")
        for row in body["data"]:
            if not isinstance(row, dict) or type(row.get("id")) is not int or row["id"] in seen:
                raise InventoryError(f"目录标识缺失或分页重复：{path}")
            seen.add(row["id"])
            rows.append(row)
        if len(rows) == total:
            return rows
        if len(rows) > total or len(body["data"]) != size:
            raise InventoryError(f"目录分页缺失，保留上次清单：{path}")
    raise InventoryError(f"目录页数超过保护上限：{path}")


def names(value):
    if not isinstance(value, list):
        return []
    return sorted({item["name"].strip() for item in value if isinstance(item, dict)
                   and isinstance(item.get("name"), str) and item["name"].strip()})


def repository_url(value):
    if not isinstance(value, str) or any(ord(c) < 33 for c in value):
        return ""
    try:
        parts = urlsplit(value)
        if parts.scheme not in {"http", "https"} or not parts.hostname or parts.username or parts.password:
            return ""
        # Repository links need neither query parameters nor fragments. Do not
        # copy potentially sensitive URL parameters into a maintained document.
        return urlunsplit((parts.scheme, parts.netloc, parts.path, "", ""))
    except ValueError:
        return ""


def build_inventory(teams, apps):
    platform = [team for team in teams if team.get("departmentID") == DEPARTMENT_ID]
    if not platform or any(team.get("departmentSlug") != DEPARTMENT_SLUG for team in platform):
        raise InventoryError("未能确认平台研发部的团队归属，保留上次清单。")
    team_map = {team["id"]: team for team in platform}
    selected = []
    for app in apps:
        if app.get("team") not in team_map:
            continue
        detail = app.get("teamDetail")
        if (
            not isinstance(detail, dict) or detail.get("id") != app["team"]
            or detail.get("departmentID") != DEPARTMENT_ID
            or detail.get("departmentSlug") != DEPARTMENT_SLUG
            or not isinstance(app.get("name"), str) or not app["name"].strip()
        ):
            raise InventoryError("应用与团队归属不一致，保留上次清单。")
        selected.append({
            "id": app["id"], "name": app["name"], "team_id": app["team"],
            "type": app.get("typeName") or "未登记", "description": app.get("description") or "",
            "tech_stack": app.get("techStack") or "", "service_level": app.get("serviceLevelName") or "",
            "repository": repository_url(app.get("repoURL")), "namespace": app.get("namespace") or "",
            "clusters": sorted(set(app.get("clusters") or [])),
            "maintainers": names(app.get("maintainers")), "developers": names(app.get("developers")),
        })
    return {
        "department_id": DEPARTMENT_ID, "department_slug": DEPARTMENT_SLUG,
        "department_name": platform[0]["departmentName"],
        "catalog_team_count": len(teams), "catalog_app_count": len(apps),
        "teams": [{"id": team["id"], "name": team["name"],
                   "maintainers": names(team.get("maintainers"))}
                  for team in sorted(platform, key=lambda row: row["id"])],
        "services": sorted(selected, key=lambda row: (row["team_id"], row["name"], row["id"])),
    }


def cell(value):
    if isinstance(value, list):
        value = "、".join(value)
    return html.escape(" ".join(str(value or "—").split()), quote=False).replace("|", "&#124;").replace("`", "&#96;")


def render_document(snapshot, previous=None):
    services, teams = snapshot["services"], snapshot["teams"]
    counts = Counter(row["team_id"] for row in services)
    types = Counter(row["type"] for row in services)
    lines = [
        MARKER, "# 平台研发团队服务清单", "",
        f"最后成功更新：{snapshot['updated_at']}（北京时间，Asia/Shanghai）。", "",
        f"共 **{len(services)} 个注册应用/服务**，归属 **{len(teams)} 个团队**。"
        f"本次完整核对 {snapshot['catalog_team_count']} 个团队、{snapshot['catalog_app_count']} 个应用，按应用 ID 去重。", "",
        "## 归属口径与数据来源", "",
        "- 以 Crane 中部门 ID `3`、部门标识 `platform`（平台研发部）下的团队为准，每次更新重新获取团队列表。",
        "- 遍历完整应用目录，按应用的 `team` ID 归属筛选；包括 service、consumer、前端等所有登记类型，不依赖服务名称前缀或个人应用列表。",
        "- 本清单是服务归属台账，不是在线运行清单；关联集群不表示当前正在运行。未登记的信息以“—”显示。",
        "- 仅保留服务资料及人员姓名，不包含凭据、Webhook、员工编号或聊天 ID。",
        "- 来源：[Crane 团队目录](https://crane-api.aihuishou.com/api/v1/teams)、[Crane 应用目录](https://crane-api.aihuishou.com/api/v1/apps)，通过本机已认证的 `cockpit api GET` 分页读取。", "",
        "## 团队汇总", "",
        "| 团队 ID | 团队 | 应用/服务数 | 团队负责人 |", "| --- | --- | ---: | --- |",
    ]
    lines.extend(f"| {team['id']} | {cell(team['name'])} | {counts[team['id']]} | {cell(team['maintainers'])} |" for team in teams)
    lines.extend(["", "类型分布：" + "；".join(f"{cell(kind)} {count}" for kind, count in sorted(types.items())) + "。", "", "## 本次变化", ""])
    if previous:
        before, after = ({row["id"]: row for row in data["services"]} for data in (previous, snapshot))
        added, removed = after.keys() - before.keys(), before.keys() - after.keys()
        changed = {key for key in before.keys() & after.keys() if before[key] != after[key]}
        lines.append(f"相较 {previous['updated_at']}：新增 {len(added)}，移出 {len(removed)}，资料或归属变更 {len(changed)}。移出不等于服务已停用。")
        for label, keys, mapping in (("新增", added, after), ("移出", removed, before), ("变更", changed, after)):
            if keys:
                lines.append(f"- {label}：" + "、".join(f"{cell(mapping[key]['name'])}（{key}）" for key in sorted(keys)))
    else:
        lines.append("首次建立完整清单。")
    for team in teams:
        lines.extend([
            "", f"## {cell(team['name'])}（{counts[team['id']]}）", "",
            "| 服务（ID） | 类型 / 技术栈 | 说明 | 应用负责人 | 开发者 | 等级 | 代码仓库 | 命名空间 / 关联集群 |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |",
        ])
        for row in services:
            if row["team_id"] != team["id"]:
                continue
            repository = "[仓库](<" + quote(row["repository"], safe="/:@%._~!$&'*+,;=-") + ">)" if row["repository"] else "—"
            fields = [
                f"{cell(row['name'])}（{row['id']}）", cell([row["type"], row["tech_stack"]] if row["tech_stack"] else row["type"]),
                cell(row["description"]), cell(row["maintainers"]), cell(row["developers"]), cell(row["service_level"]), repository,
                cell(row["namespace"]) + " / " + cell(row["clusters"]),
            ]
            lines.append("| " + " | ".join(fields) + " |")
    lines.extend([
        "", "## 每日维护", "",
        "- 每天北京时间 15:00 由本机 LaunchAgent `com.octopus.assistant.platform-services` 更新本文件。",
        "- 定时任务依赖当前 macOS 用户登录、cockpit 认证有效及内网可达。系统时区需保持 Asia/Shanghai；休眠错过时会在唤醒后补跑，关机或退出登录期间无法按时运行。",
        "- 获取失败、分页不完整或归属信息冲突时保留上次成功清单；不会将查询失败当作服务被删除。",
        "- 手动更新：`.venv/bin/python scripts/update_platform_services.py`。",
        "- 查看定时状态：`.venv/bin/python scripts/platform_services_schedule.py status`。",
        "- 本文件由脚本整体生成；修改归属应在 Crane 中完成。运行结果保存在 `.data/platform-services/last-run.json`。", "",
    ])
    return "\n".join(lines)


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as output:
            output.write(content)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def update_inventory(client, *, document=DOCUMENT, runtime=RUNTIME):
    previous_path = runtime / "snapshot.json"
    if document.exists() and not document.read_text().startswith(MARKER):
        raise InventoryError("目标文档不是本脚本生成，未覆盖。")
    previous = json.loads(previous_path.read_text()) if previous_path.exists() else None
    teams = fetch_all(client, "/api/v1/teams", {"includingUser": "true"})
    apps = fetch_all(client, "/api/v1/apps", {"onlyMine": "false", "isShowDetail": "true"})
    snapshot = build_inventory(teams, apps)
    snapshot["updated_at"] = datetime.now(TIMEZONE).isoformat(timespec="seconds")
    rendered = render_document(snapshot, previous)
    atomic_write(document, rendered)
    atomic_write(previous_path, json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n")
    return {"status": "updated", "updated_at": snapshot["updated_at"], "services": len(snapshot["services"]),
            "teams": len(snapshot["teams"]), "catalog_apps": len(apps), "document": str(document)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cockpit", default="cockpit", help="Path to the authenticated cockpit executable")
    args = parser.parse_args()
    RUNTIME.mkdir(parents=True, exist_ok=True)
    with (RUNTIME / "update.lock").open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print(json.dumps({"status": "already_running"}))
            return 0
        try:
            result = update_inventory(Cockpit(args.cockpit))
        except (InventoryError, OSError, ValueError, KeyError, TypeError) as exc:
            result = {"status": "failed", "attempted_at": datetime.now(TIMEZONE).isoformat(timespec="seconds"),
                      "error": str(exc) if isinstance(exc, InventoryError) else "更新失败，未完成本次同步；请检查本地文件和目录响应。"}
        atomic_write(RUNTIME / "last-run.json", json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        print(json.dumps(result, ensure_ascii=False))
        return 0 if result["status"] == "updated" else 1


if __name__ == "__main__":
    raise SystemExit(main())
